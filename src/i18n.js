function interpolate(template, values = {}) {
  return template.replace(/\{(\w+)\}/g, (_, key) => String(values[key] ?? ""));
}

export function normalizeLocale(locale) {
  const language = String(locale ?? "").toLowerCase().split("-")[0];
  return SUPPORTED_LOCALES.includes(language) ? language : "en";
}

export function translate(locale, key, values = {}) {
  const normalized = normalizeLocale(locale);
  const template = messages[normalized][key] ?? messages.en[key] ?? key;
  return interpolate(template, values);
}

export function translateCalculatorError(locale, error) {
  if (!error?.code) return translate(locale, "unableToCalculate");

  const values = { ...error.values };
  if (error.code === "functionArgumentCount") {
    values.argumentWord = translate(
      locale,
      values.count === 1 ? "argument" : "arguments",
    );
  }

  return translate(locale, error.code, values);
}
